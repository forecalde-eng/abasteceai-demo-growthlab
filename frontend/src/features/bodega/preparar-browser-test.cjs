async (page) => {
  const base = page.url().split("/").slice(0, 3).join("/");
  const path = "/src/features/bodega/pruebas/preparar.html";
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const calls = () => page.evaluate(async () => (await import("/src/features/bodega/pruebas/fixture.ts")).calls);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + path);
  const preview = page.getByRole("button", { name: "Vista previa FEFO", exact: true });
  const confirm = page.getByRole("button", { name: "Confirmar preparación", exact: true });
  check(await confirm.isDisabled(), "No confirma sin vista previa");
  await preview.click();
  await page.getByRole("table", { name: "Plan FEFO", exact: true }).waitFor();
  check((await calls()).every((entry) => entry.dryRun), "La vista previa no confirma");
  check(!(await page.locator("body").innerText()).includes("DEMO-002-VENC"), "No muestra lotes vencidos");
  check(await confirm.isEnabled(), "Plan válido habilita confirmación humana");
  const amount = page.getByLabel("Preparado INS-001", { exact: true });
  await amount.fill("999");
  check(await confirm.isDisabled() && await preview.isDisabled(), "No supera aprobación y la edición invalida el plan");
  check(await page.getByRole("table", { name: "Plan FEFO", exact: true }).count() === 0, "No conserva un plan obsoleto");
  await amount.fill("-1"); check(await preview.isDisabled(), "No admite negativos");
  await amount.fill("0.0001"); check(await preview.isDisabled(), "No admite más de tres decimales");
  await amount.fill("2");
  await preview.click();
  await page.getByRole("table", { name: "Plan FEFO", exact: true }).waitFor();
  await confirm.evaluate((button) => { button.click(); button.click(); });
  await page.getByText("Respuesta de confirmación recibida", { exact: true }).waitFor();
  await page.getByText("INC-EMPAQUE", { exact: true }).waitFor();
  check((await calls()).filter((entry) => !entry.dryRun).length === 1, "Doble clic envía una sola confirmación");
  check((await page.getByText("En preparación", { exact: true }).count()) >= 1, "La diferencia conserva preparing devuelto por el servicio");
  check(await confirm.isDisabled(), "No permite reconfirmar tras éxito");
  const text = await page.locator("body").innerText();
  check(!/[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}/i.test(text), "Sin UUID visibles");
  await page.reload();
  await page.evaluate(async () => (await import("/src/features/bodega/pruebas/fixture.ts")).setMode("expired"));
  await preview.click();
  await page.getByText("El servicio devolvió un lote vencido al reloj de demo. No se puede confirmar este plan.", { exact: true }).waitFor();
  check(await confirm.isDisabled(), "Respuesta con lote vencido bloqueada");
  check(await page.getByRole("table", { name: "Plan FEFO", exact: true }).count() === 0, "No presenta la propuesta inválida");
  await page.evaluate(async () => (await import("/src/features/bodega/pruebas/fixture.ts")).setMode("error"));
  await preview.click();
  await page.getByText("El pedido cambió de estado. Solicita una nueva vista previa.", { exact: true }).waitFor();
  check(await confirm.isDisabled(), "El error no se interpreta como confirmación");
  await page.goto(base + path + "?pedido=PED-DEMO-006");
  await preview.click();
  await page.getByRole("table", { name: "Plan FEFO", exact: true }).waitFor();
  await confirm.click();
  await page.getByText("Listo", { exact: true }).first().waitFor();
  await page.setViewportSize({ width: 375, height: 812 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Sin desbordamiento de página a 375 px");
  console.log("UI B-2.2: vista previa, invalidación, confirmación única, errores y estados del contrato OK. No prueba fn_preparar real.");
}
