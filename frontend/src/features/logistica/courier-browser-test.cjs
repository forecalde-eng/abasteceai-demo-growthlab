async (page) => {
  const base = page.url().split('/').slice(0, 3).join('/')
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const role = (value) => page.evaluate((name) => {
    localStorage.setItem('abasteceai.dev.role', name)
    window.dispatchEvent(new Event('abasteceai:role-change'))
  }, value)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(base + '/')
  await role('logistica')
  await page.goto(base + '/logistica/courier')
  const table = page.getByRole('table', { name: 'Envíos courier', exact: true })
  await table.waitFor()
  const row = table.getByRole('row').filter({ hasText: 'ENV-DEMO-008' })
  const text = await row.innerText()
  check(await table.locator('tbody tr').count() === 1, 'Solo el courier del CSV')
  check(text.includes('G-001') && text.includes('Guayaquil') && text.includes('GUIA-DEMO-008'), 'PITCH-9: guía y destino correctos')
  check(text.includes('Despachado') && text.includes('Retrasado'), 'Estado y alerta mostrados por separado')
  check((await row.getByText('Retrasado', { exact: true }).getAttribute('class')).includes('text-red-800'), 'Alerta en tono Problema')
  check(await row.locator('time').getAttribute('datetime') === '2026-10-10T20:00:00Z', 'Fecha prometida original del CSV')
  check((await row.locator('time').innerText()).includes('15:00'), 'Promesa en hora de Guayaquil')
  check((await page.locator('body').innerText()).includes('17:00'), 'Reloj de demo visible en hora de Ecuador')
  check((await page.locator('body').innerText()).includes('DEMO FICTICIA'), 'Banner visible')
  check(!/[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}/i.test(await page.locator('body').innerText()), 'Sin UUID visibles')

  await page.getByLabel('Seguimiento', { exact: true }).selectOption('delayed')
  check(await table.locator('tbody tr').count() === 1, 'Filtro de retrasados')
  const search = page.getByLabel('Buscar envío, guía o destino')
  await search.fill('NO-EXISTE')
  await page.getByText('Sin envíos courier para mostrar', { exact: true }).waitFor()
  await search.fill('G-001')
  await row.waitFor()
  await search.fill('')
  await row.getByRole('link', { name: 'Ver etiqueta', exact: true }).click()
  await page.getByRole('img', { name: 'QR de GUIA-DEMO-008', exact: true }).waitFor()
  check(page.url().endsWith('/despacho?envio=ENV-DEMO-008'), 'Enlace existente a etiqueta por código')
  await page.goto(base + '/logistica/courier')
  await table.waitFor()
  await page.setViewportSize({ width: 375, height: 812 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sin desbordamiento de página a 375 px')

  await role('auxiliar')
  await page.getByText('No tienes acceso a esta pantalla', { exact: true }).waitFor()
  check(await page.getByRole('table').count() === 0, 'Auxiliar sin acceso a Courier')

  // Usa el reemplazo compartido existente, sin inventar otro endpoint ni entrega.
  await role('supervisor')
  await page.evaluate(async () => {
    const { markDelivered } = await import('/src/app/dev/apiDemo.ts')
    const { shipments } = await import('/src/mocks/shipments.ts')
    await markDelivered(shipments.find((entry) => entry.code === 'ENV-DEMO-008').id)
  })
  await role('logistica')
  await table.waitFor()
  await row.getByText('Entregado sin conteo', { exact: true }).waitFor()
  await row.getByText('Sin alerta de retraso', { exact: true }).waitFor()
  check(await row.getByText('Retrasado', { exact: true }).count() === 0, 'Retira la alerta del snapshot tras una entrega en la sesión')

  await page.route('**/src/mocks/demoMetadata.ts*', (route) => route.fulfill({ contentType: 'application/javascript', body: 'export const demoMetadata = [];' }))
  await page.reload()
  await page.getByText('No se pudieron cargar los envíos courier', { exact: true }).waitFor()
  check(await table.count() === 0, 'Un reloj ausente no se muestra como ausencia de retrasos')
  await page.unroute('**/src/mocks/demoMetadata.ts*')
  await page.reload()
  await table.waitFor()
  check(errors.length === 0, `Errores JavaScript: ${errors.join(', ')}`)
  console.log('B-4.3: PITCH-9, SQL y reloj de demo, filtros, guía, permisos, móvil, entrega compartida y error de referencia OK.')
}
